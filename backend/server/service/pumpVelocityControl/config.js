/**
 * 【文件职责】水泵恒流速控制的兜底参数。逻辑在同目录 pumpVelocityControl.js。
 * 【值的来源】从原"配置中心"持久化文件固化下来的当前实际生效值。改完重启后端生效。
 * 【谁在读】pumpVelocityControl.js 本身；averageChartQuery 拿它算目标流速参考线。
 *
 * 水泵只有开关量、没有变频调速，用两套互斥算法把"开关"逼近"恒定流速"：
 *   'hysteresis' 滞环通断：流速低于"目标-回差"开泵，达到目标关泵，中间维持现状。简单、不用整定，
 *                但流速几乎没惯性，必须靠最小开/关时长限制启停频率，否则短循环（频繁启停烧电机）。
 *   'pid'        占空比控制：固定周期内按 PID 算出的占空比决定水泵开多久关多久，调周期内平均流速。
 * 被控量是管内平均流速 v = Q / A，由 field3(L/min) 和 config/metrics.js 的 pipeAreaCm2 换算；
 * 没配 pipeAreaCm2 就算不出流速，本模块整轮不动作并打日志。
 * 启用后接管水泵；故障状态和安全联锁是更高优先级的独立保护层，触发后照样强制关泵。
 * 每个数值参数在指令中心都有对应指令项，指令项优先，删掉指令项才退回这里。
 */
module.exports = {
  enabled: false,              // 兜底总开关（仅在指令中心两个算法开关都没配时才看这里）
  mode: 'hysteresis',          // 兜底算法：'hysteresis' 滞环通断 / 'pid' 占空比
  defaultTargetVelocity: 1,    // 目标流速兜底值（m/s），两套算法共用的唯一设定值
  hysteresis: 0.1,             // 滞环回差（m/s），滞环通断专用
  minOnMs: 15000,              // 最小开启时长（ms），两套算法共用的防短循环保护
  minOffMs: 15000,             // 最小关闭时长（ms）
  windowMs: 30000,             // 占空比控制周期（ms），实际不低于 10000（水泵启停冲击大）
  kp: 100,                     // 占空比控制 PID 参数，误差 = 目标流速 - 当前流速
  ki: 5,
  kd: 0,
  deadband: 0.02,              // 流速死区（m/s），误差小于它就保持上一次占空比
  dutyMin: 0,                  // 占空比下限（%）
  dutyMax: 100,                // 占空比上限（%）
  derivativeFilter: 0.3,       // 微分项一阶低通滤波系数 0~1，越小滤波越强
  dutyRampLimit: 15,           // 占空比斜率限制(%/周期)，0=不限制
}
