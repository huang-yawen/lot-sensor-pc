/**
 * 【文件职责】数据质量板块的开关与参数。本板块与「安全联锁」「故障状态」平级，
 * 目前包含两条规则，逻辑分别在同目录：
 *   规则一 spikeFilter.js  传感器数值跳变/毛刺  —— 检测 + 防抖过滤 + 轻微告警
 *   规则二 relayStuck.js   继电器触点粘连/控制失效 —— 检测 + 自动重发关闭指令 + 硬件故障判定
 *   规则三 sensorInverted.js 逆温差/传感器装反 —— 检测 + 提示检查硬件拓扑 + 暂停恒温控制
 * 【值的来源】新增板块，下面是首次设定的默认值。改完重启后端生效。
 * 【谁在读】spikeFilter.js / relayStuck.js / sensorInverted.js 本身；config/systemConfig.js（拼进
 * GET /api/system-config 给前端读 showOnErrorPage）。
 * 当前状态：板块总开关开着（enabled=true），三条规则都开着。
 */
module.exports = {
  // 板块总开关。关掉后两条规则都不生效（数据一律原样入库、不做任何检测）。
  enabled: false,

  // 故障记录页是否显示"数据质量记录"表格（只控制前端展示，不影响检测和写库）。
  showOnErrorPage: true,

  // ==================== 规则一：传感器数值跳变 / 毛刺 ====================
  // 判定口径：跳变 = |本次值 − 上次已确认值| / |上次已确认值| > ratio。
  // 处置：跳变值不直接入库，先进内存缓冲区，连续 confirmCount 次确认站得住才补写进库；
  //       中途跳回去就整批丢弃，永不入库。详见 spikeFilter.js 文件头。
  spikeFilter: {
    // 本条规则开关（受上面板块总开关 enabled 约束，两个都 true 才生效）。
    // 关掉后传感器数据一律原样入库、不检测跳变、不写"数据质量"记录，
    // 规则二、规则三不受影响——赛场调试时想单独排除"是不是毛刺过滤把数据拦了"就关它，
    // 不要去关板块总开关（那会把继电器粘连、传感器装反检测一起关掉）。
    enabled: true,

    // 跳变判定比例。0.5 = ±50%：本次值相对上次已确认值变化超过 50% 就视为疑似跳变。
    ratio: 0.2,
    // 连续采集多少次确认。3 = 跳变后再收 2 条（共 3 条）都稳定在新水位，才认这是真实
    // 阶跃、把这 3 条补写进库；中途跳回去就把这几条当毛刺整批丢弃。
    confirmCount: 3,

    // 逐字段启用开关。key 是 appSettings.js 里 SENSOR_FIELD_MAP 的语义槽位名，
    // 不是 field1/field2（物理字段改了这里不用跟着改）。设 false 即不监控该字段。
    fields: {
      temp1: true,     // 进水温度
      temp2: true,     // 出水温度
      flow: true,      // 瞬时流量
      pressure: true,  // 瞬时压力
    },

    // 参照值下限：上次已确认值的绝对值小于它就跳过比例判定。
    // 为什么需要：①上次值为 0 时除法直接是 Infinity，任何读数都会被判成跳变；
    // ②比例在 0 附近没有物理意义——0.1℃ → 0.2℃ 是 +100%，但实际只差 0.1℃，
    // 按 ±50% 判会把传感器在零点附近的正常噪声全部当成毛刺。
    minBase: 0.2,

    // 水泵预热期内（水泵已开、但还没连续开满预热时长）flow / pressure 两个字段不判跳变：
    // 泵刚启动时流量、压力从 0 往上爬，每条都变化很大，不跳过会每次开泵都被当成毛刺。
    // 泵关着时照常判。预热时长不在本文件：指令中心"水泵预热宽限期(ms)"（pump_warmup_ms）
    // 优先，没配才用 faultStatus/config.js 的 pumpWarmupMs，跟安全联锁、告警、故障机共用一份。

    // 缓冲区最长滞留时间（毫秒）。设备突然停发、或采集间隔临时变长时，攒在缓冲区里的
    // 数据不能永远卡在内存里等确认，超过这个时间强制放行补写。按 1 秒采集间隔算，
    // 10 秒足够收满 confirmCount 条；现场采集间隔更慢时要同步调大。
    maxPendingMs: 10000,

    // 同一个字段的跳变告警冷却时间（毫秒），跟安全联锁/故障状态机同一套语义：
    // 冷却期内即使又跳变也不重复写记录、不重复弹提示（过滤本身照常生效）。
    alarmCooldownMs: 30000,
  },

  // ==================== 规则二：继电器触点粘连 / 控制失效 ====================
  // 判定口径：指令为"关"，但传感器显示设备仍在工作，且持续超过观察期。
  // 处置：①报"实际状态与控制指令不符" ②自动重发 retryCount 次关闭指令
  //       ③全部无效则判定硬件故障、提示人工断电检修并停止重试。详见 relayStuck.js 文件头。
  relayStuck: {
    enabled: false,          // 本条规则开关（受上面板块总开关 enabled 约束）

    heater: true,           // 是否检测加热器（靠出水温度是否还在上升反推）
    pump: true,             // 是否检测水泵（靠瞬时流量是否还不为 0 反推）

    // 加热器观察期（毫秒）。加热丝断电后热量还会继续传给水，出水温度短时间内继续
    // 爬升是正常物理现象，必须等过这段余热期再判，否则每次正常关加热都会误报。
    heaterConfirmMs: 10000,
    // 观察期后，出水温度相对"指令转关那一刻"的基准还上升超过这么多（℃），
    // 就认为加热其实没断电。调大 = 更保守、更不容易误报。
    heaterRiseC: 0.3,

    // 水泵观察期（毫秒）。管路里有惯性余流，泵停之后流量不是立刻归零。
    pumpConfirmMs: 5000,
    // 观察期后，瞬时流量还大于等于这个值（L/min）就认为水泵其实没停。
    // 要比流量计的零点噪声大，否则静止时的抖动会被当成"泵还在转"。
    pumpFlowMin: 0.1,

    // 自动重发关闭指令的次数和间隔。发满 retryCount 次仍未恢复才判硬件故障。
    retryCount: 3,
    retryIntervalMs: 3000,
  },

  // ==================== 规则三：逆温差 / 传感器装反 ====================
  // 判定口径：出水温度 < 进水温度，且温差 > tempDiffThreshold，
  //           同时加热模块已开启超过 heatingMinMs。
  // 处置：①报"传感器逻辑配置异常"，提示检查硬件拓扑 ②暂停自动恒温控制，
  //       防止 PID 因为被控量方向反了而正反馈超温。详见 sensorInverted.js 文件头。
  sensorInverted: {
    enabled: false,

    // 进水 − 出水 超过这么多（℃）才算"逆温差"。要比两路传感器之间的测量误差大，
    // 否则两个探头本身的偏差就会误报。
    tempDiffThreshold: 0.3,

    // 加热模块开启超过这么久（毫秒，默认 3 分钟）才开始判。刚开加热时水还没热起来，
    // 出水比进水冷是正常的。
    heatingMinMs: 180000,

    // 加热"连续关闭"超过这么久（毫秒）才认为本轮加热结束、把上面那个计时清零。
    // 为什么需要：PID 恒温是时间比例控制，加热开关会被高频通断，一关就清零的话
    // 3 分钟永远攒不满、这条规则等于失效。
    heatingOffResetMs: 30000,

    // 判定成立后是否暂停自动恒温控制（pidHeating）。设 false 就只报警不停机。
    suspendThermostat: true,
  },
}
