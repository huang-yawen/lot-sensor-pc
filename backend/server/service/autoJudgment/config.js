/**
 * 【文件职责】自动判定模式的节奏参数。逻辑在同目录 autoJudgment.js。
 *
 * 【和手动模式的分工】判定服务"长什么样"——地址、请求方法、请求体字段名、从响应哪个
 * 路径取结论——两种模式完全共用，配在 controllers/intelligent/config.js，不要在这里
 * 再配一遍。本文件只管自动模式特有的"怎么跑"：多久跑一次、每次取几条、页面留多少条。
 *
 * 【值的来源】新增功能，这里是初始生效值。改完重启后端生效（定时器启动时读一次）。
 * 【谁在读】autoJudgment.js；另外经 config/systemConfig.js 拼进 GET /api/system-config，
 *           前端读 showMenu 决定"自动判定"菜单显隐、读 intervalMs 显示当前节奏。
 *
 * ══════════════ 赛场按赛题怎么配 ══════════════
 * | 赛题这么要求                      | 这么配                                        |
 * |----------------------------------|----------------------------------------------|
 * | "实时判定"、要看着数就变           | intervalMs: 1000, recentCount: 1             |
 * | "每隔 N 秒判一次最近若干条"         | intervalMs: N*1000, recentCount 按赛题给的条数  |
 * | 判定服务响应慢（比如要 3 秒）        | intervalMs 配到比它慢，如 5000——配太快只会一直  |
 * |                                  | 打印"上一轮还没判完，跳过这一轮"，白跑            |
 * | 只要手动判定，不要自动             | enabled: false（默认就是），菜单也会自动隐藏      |
 * | 要演示但现场还没给判定服务           | 本文件 enabled: true +                        |
 * |                                  | controllers/intelligent/config.js 的 enabled: false |
 * |                                  | → 走本地占位判定，整条链路和三张图都能动          |
 * | 演示时间长、要看长趋势              | bufferSize 调大（上限 500）                    |
 *
 * 要改"判哪张表、只判某台设备"这类取数规则，不在本文件，在同目录 autoJudgment.js
 * 的 runOnce()——那里的文件头注释有对照表。
 */
module.exports = {
  // 自动判定总开关。false 时后端不启动定时器，前端也不显示菜单入口。
  // 注意跟 controllers/intelligent/config.js 里的 enabled 不是一回事：
  //   那个 enabled  = 判定结果是真找现场服务要，还是用本地占位判定
  //   这个 enabled  = 要不要开"每隔几秒自动提交"这套定时逻辑
  // 所以"本地占位判定 + 自动模式"可以同时开，赛前没有判定服务时也能演示整条链路。
  enabled: false,

  // 每隔多少毫秒提交一次。下限 1000——比这更快会把判定服务和数据库打满，
  // 配了小于 1000 的值会被自动抬到 1000。
  intervalMs: 5000,

  // 每次提交最新多少条传感器数据（按 c_time 倒序取，提交时再翻回时间正序）。
  recentCount: 5,

  // 后端内存里保留最近多少次判定结果，供"自动判定"页的图表渲染和页面首次加载。
  // 只影响图表能看到多长的趋势；完整历史在 t_judgment_record 里，查"智能判定记录"页。
  bufferSize: 50,

  showMenu: true,   // 左侧菜单是否显示"自动判定"页
}
